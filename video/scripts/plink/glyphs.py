"""Export glyph outlines as SVG path strings (1 unit = 1 em, y down, centred)
so three.js can extrude them. usage: glyphs.py font.woff out.ts chars"""
import json, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

font_path, out, chars = sys.argv[1], sys.argv[2], sys.argv[3]
f = TTFont(font_path)
gs, cmap, upm = f.getGlyphSet(), f.getBestCmap(), f["head"].unitsPerEm
res = {}
for ch in chars:
    name = cmap[ord(ch)]
    bp = BoundsPen(gs); gs[name].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.4f}".rstrip("0").rstrip("."))
    # centre on the glyph box, scale to em, flip y for SVG
    gs[name].draw(TransformPen(pen, (1 / upm, 0, 0, -1 / upm, -cx / upm, cy / upm)))
    res[ch] = {"d": pen.getCommands(), "w": (x1 - x0) / upm, "h": (y1 - y0) / upm}
with open(out, "w") as fh:
    fh.write("// Generated by glyphs.py from Inter Black: centred outlines, 1 unit = 1 em, y down.\n")
    fh.write("export const GLYPHS: Record<string, { d: string; w: number; h: number }> = " + json.dumps(res, ensure_ascii=False, indent=1) + ";\n")
print({k: (round(v["w"], 3), round(v["h"], 3), len(v["d"])) for k, v in res.items()})
